export function getVideoById(id) {
  return videos.find((v) => String(v.id) === String(id));
}

// Same as above but also checks user uploads (client-side)
export function getAnyVideo(id) {
  if (typeof window === "undefined") return getVideoById(id);
  try {
    const uploads = JSON.parse(localStorage.getItem("yt-uploads") || "[]");
    const hit = uploads.find((v) => String(v.id) === String(id));
    if (hit) return hit;
  } catch {}
  return getVideoById(id);
}

export function getShort(id) {
  return shorts.find((s) => String(s.id) === String(id));
}

export function searchVideos(term) {
  const q = term.trim().toLowerCase();
  if (!q) return [];
  return videos.filter((v) =>
    `${v.title} ${v.channel} ${v.description} ${v.category}`
      .toLowerCase()
      .includes(q)
  );
}

// Search across uploads + catalog (client-side; falls back to catalog on server)
export function searchAll(term) {
  const q = term.trim().toLowerCase();
  if (!q) return [];
  const pool = typeof window === "undefined" ? videos : allVideos();
  return pool.filter((v) =>
    `${v.title} ${v.channel} ${v.description || ""} ${v.category}`
      .toLowerCase()
      .includes(q)
  );
}

export function filterByChip(chip) {
  if (!chip || chip === "All") return videos;
  if (chip === "Live") return videos.filter((v) => v.uploadedAt === "LIVE" || v.duration === "LIVE");
  return videos.filter((v) => v.category === chip);
}

export function formatCount(n) {
  if (n >= 1000000) return `${(n / 1000000).toFixed(1).replace(/\.0$/, "")}M`;
  if (n >= 1000) return `${(n / 1000).toFixed(1).replace(/\.0$/, "")}K`;
  return String(n);
}

// ---- recommendations: score by your local signals ----
function signalMaps() {
  const empty = { cats: {}, channels: {} };
  if (typeof window === "undefined") return empty;
  try {
    const history = JSON.parse(localStorage.getItem("yt-history") || "[]");
    const liked = JSON.parse(localStorage.getItem("yt-liked") || "{}");
    const subs = JSON.parse(localStorage.getItem("yt-subs") || "[]");
    const byId = {};
    [...videos].forEach((v) => (byId[String(v.id)] = v));
    try {
      const uploads = JSON.parse(localStorage.getItem("yt-uploads") || "[]");
      uploads.forEach((v) => (byId[String(v.id)] = v));
    } catch {}
    history.slice(0, 30).forEach((id, i) => {
      const v = byId[String(id)];
      if (!v) return;
      const w = 30 - i; // recent watches weigh more
      empty.cats[v.category] = (empty.cats[v.category] || 0) + w;
      empty.channels[v.channel] = (empty.channels[v.channel] || 0) + w;
    });
    Object.keys(liked).forEach((id) => {
      if (liked[id] !== "like") return;
      const v = byId[String(id)];
      if (!v) return;
      empty.cats[v.category] = (empty.cats[v.category] || 0) + 60;
      empty.channels[v.channel] = (empty.channels[v.channel] || 0) + 60;
    });
    subs.forEach((c) => {
      empty.channels[c] = (empty.channels[c] || 0) + 80;
    });
  } catch {}
  return empty;
}

export function scoreVideo(v, maps, currentId = null) {
  if (String(v.id) === String(currentId)) return -Infinity;
  let s = Math.log10((v.viewsCount || 1) + 10); // base popularity
  s += (maps.cats[v.category] || 0) / 25;
  s += (maps.channels[v.channel] || 0) / 20;
  if (v.uploadedAt === "Just now" || v.uploadedAt?.includes("day")) s += 0.6; // fresh boost
  if (v.uploadedAt === "LIVE") s += 1.2;
  return s;
}

// Rank a list by affinity; returns new array (no signals → popularity order)
export function rankVideos(list, currentId = null) {
  const maps = signalMaps();
  const hasSignals =
    Object.keys(maps.cats).length > 0 || Object.keys(maps.channels).length > 0;
  if (!hasSignals) return [...list].sort((a, b) => (b.viewsCount || 0) - (a.viewsCount || 0));
  return [...list]
    .map((v, i) => ({ v, s: scoreVideo(v, maps, currentId), i }))
    .sort((a, b) => b.s - a.s || a.i - b.i)
    .map((x) => x.v);
}

export function hasSignals() {
  const m = signalMaps();
  return Object.keys(m.cats).length > 0 || Object.keys(m.channels).length > 0;
}

// ---- persistence helpers (watch history, likes, subs, comments) ----
const read = (key, fallback) => {
  if (typeof window === "undefined") return fallback;
  try {
    const raw = localStorage.getItem(key);
    return raw ? JSON.parse(raw) : fallback;
  } catch {
    return fallback;
  }
};
const write = (key, value) => {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(key, JSON.stringify(value));
  } catch {}
};

export const store = {
  getLiked: (id) => read("yt-liked", {})[id] ?? null,
  setLiked: (id, val) => {
    const all = read("yt-liked", {});
    if (!val) delete all[id];
    else all[id] = val;
    write("yt-liked", all);
  },
  isSubscribed: (channel) => read("yt-subs", []).includes(channel),
  toggleSub: (channel) => {
    const list = read("yt-subs", []);
    const next = list.includes(channel)
      ? list.filter((c) => c !== channel)
      : [...list, channel];
    write("yt-subs", next);
    return next.includes(channel);
  },
  pushHistory: (id) => {
    const h = read("yt-history", []);
    write("yt-history", [id, ...h.filter((x) => x !== id)].slice(0, 50));
  },
  bumpViews: (id) => {
    const v = read("yt-views", {});
    v[id] = (v[id] || 0) + 1;
    write("yt-views", v);
    return v[id];
  },
  getComments: (id) => read(`yt-comments-${id}`, null),
  setComments: (id, list) => write(`yt-comments-${id}`, list),
  // Watch progress: {time, dur} per video id
  getProgress: (id) => read("yt-progress", {})[String(id)] || null,
  setProgress: (id, time, dur) => {
    const all = read("yt-progress", {});
    if (!dur || time < 10 || time > dur - 15) {
      delete all[String(id)];
    } else {
      all[String(id)] = { time: Math.floor(time), dur: Math.floor(dur) };
    }
    write("yt-progress", all);
  },
  clearProgress: (id) => {
    const all = read("yt-progress", {});
    delete all[String(id)];
    write("yt-progress", all);
  },
  // Watch Later
  getWatchLater: () => read("yt-watchlater", []),
  isWatchLater: (id) => read("yt-watchlater", []).some((x) => String(x) === String(id)),
  toggleWatchLater: (id) => {
    const list = read("yt-watchlater", []).map(String);
    const sid = String(id);
    const next = list.includes(sid) ? list.filter((x) => x !== sid) : [sid, ...list];
    write("yt-watchlater", next);
    return next.includes(sid);
  },
  // Playlists: [{id, name, ids:[]}]
  getPlaylists: () => read("yt-playlists", []),
  createPlaylist: (name) => {
    const list = read("yt-playlists", []);
    const pl = { id: `pl-${Date.now()}`, name: name.trim() || "New playlist", ids: [] };
    write("yt-playlists", [...list, pl]);
    return pl;
  },
  deletePlaylist: (pid) => write("yt-playlists", read("yt-playlists", []).filter((p) => p.id !== pid)),
  toggleInPlaylist: (pid, vid) => {
    const list = read("yt-playlists", []);
    const sid = String(vid);
    const next = list.map((p) =>
      p.id !== pid ? p : { ...p, ids: p.ids.includes(sid) ? p.ids.filter((x) => x !== sid) : [...p.ids, sid] }
    );
    write("yt-playlists", next);
    return next.find((p) => p.id === pid);
  },
  // Studio uploads: full video objects with id `u-<ts>`
  getUploads: () => read("yt-uploads", []),
  addUpload: (video) => {
    const list = read("yt-uploads", []);
    write("yt-uploads", [video, ...list]);
    return video;
  },
  deleteUpload: (id) => write("yt-uploads", read("yt-uploads", []).filter((v) => String(v.id) !== String(id))),
};

// Uploads merged into catalog lookups (uploads first)
export function allVideos() {
  if (typeof window === "undefined") return [...videos];
  let uploads = [];
  try {
    uploads = JSON.parse(localStorage.getItem("yt-uploads") || "[]");
  } catch {}
  return [...uploads, ...videos];
}

// Single lookup across uploads + catalog (safe for SSR: no localStorage on server)
export function findVideo(id) {
  if (typeof window !== "undefined") {
    try {
      const uploads = JSON.parse(localStorage.getItem("yt-uploads") || "[]");
      const hit = uploads.find((v) => String(v.id) === String(id));
      if (hit) return hit;
    } catch {}
  }
  return getVideoById(id);
}

// Keyboard support for clickable rows/cards (a11y): Enter/Space activates
export function rowKey(onActivate) {
  return (e) => {
    if (e.key === "Enter" || e.key === " ") {
      e.preventDefault();
      onActivate();
    }
  };
}
